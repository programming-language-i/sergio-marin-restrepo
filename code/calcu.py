def suma(valor1, valor2):
    return valor1 + valor2

def resta(valor1, valor2):
    return valor1 - valor2
def multi (valor1, valor2):
    return valor1 * valor2

resultadoSuma = suma(5,2)
print(resultadoSuma)
resultadoResta = resta(5,2)
print(resultadoResta)
resultadoMultiplicacion = multi(5,2)
print(resultadoMultiplicacion)